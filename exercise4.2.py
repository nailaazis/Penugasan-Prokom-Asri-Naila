animals = ["Kelinci", "Kucing", "Burung", "Hamster"]

for animal in animals:
    print(f"Hewan {animal} merupakan hewan yang penurut")

if animal == "Kelinci":
    print("Kelinci makanannya mudah ditemui.")

elif animal == "Kucing":
    print("Kucing sangat menggemaskan")

elif animal == "Burung":
    print("Kicauan burung sangat indah.")
    
elif animal == "Hamster":
    print("Hamster sangat kecil dan gemas.")
   
print("\nSemua hewan sangat menggemaskan")
    