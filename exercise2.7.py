# nama
nama = "\t\n Naila \n\t"

# menampilkan nama sebelum karakter kosong dihilangkan
print("Nama asli:")
print(f">>>{nama}<<<")

print("Menggunakan lstrip():")
print(f">>>{nama.lstrip()}<<<")

print("Menggunakan rstrip():")
print(f">>>{nama.rstrip()}<<<")

print("Menggunakan strip():")
print(f">>>{nama.strip()}<<<")
